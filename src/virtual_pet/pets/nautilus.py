NAUTILUS = Species(
    key="nautilus",
    label=QT_TRANSLATE_NOOP("Species", "Nautilus"),
    palette={
        "K": "#2b1a12",  # outline
        "B": "#f2e9d6",  # the shell's white
        "G": "#d6c8ae",  # the shell's underside, in shade
        "S": "#a8402c",  # red-brown stripes
        "R": "#7e2e22",  # the stripes near the umbilicus
        "D": "#3b2418",  # the umbilicus, the aperture's dark inside, the eye's socket
        "O": "#8a5536",  # the hood
        "P": "#efe2c8",  # white dots on the hood
        "T": "#f3eee5",  # the tentacles' sheaths
        "U": "#b88f6a",  # brown bands between the sheaths
        "Q": "#c4ab93",  # thin cirri, with no outline
        "C": "#9c8a7c",  # the eye's rim
        "N": "#141014",  # the pinhole pupil
        EYE: "#efe9df",  # the eye's white bulb
        EYE_SHINE: "#efe9df",
    },
    animations={
        # Like the sea turtle and the fish, it floats between swims and only touches the ground
        # when resting. Nautiluses spend most of their time hovering, dangling their tentacles.
        Activity.STANDING: Animation((HOVER_A, HOVER_B, HOVER_C, HOVER_D), fps=1.5),
        # One jet in exactly 2 s (the gait's pulse): the head pulls into the shell over the first
        # second, which drives the jet, and comes back out as the mantle cavity refills.
        Activity.WALKING: Animation(
            (
                JET_OUT,
                JET_OUT,
                JET_HALF,
                JET_HALF,
                JET_IN,
                JET_IN,
                JET_IN,
                JET_IN,
                JET_HALF,
                JET_HALF,
                JET_OUT,
                JET_OUT,
            ),
            fps=6,
        ),
        Activity.SITTING: Animation((REST_A, REST_B), fps=0.5),  # on the bottom, one cirrus down
        Activity.CARRIED: Animation((CARRIED_A, CARRIED_B), fps=1.5),  # breathing, cirri swinging
    },
    # Most swims go shell first, in surges of one jet every 2 s (Neil & Askew 2018).
    gait=Gait(
        speed=30, max_slope=0.5, distance=(60, 240), rest=(2.0, 6.0), backward=0.77, pulse=2.0
    ),
    locomotion=Locomotion.SWIM,
    sit_label=QT_TRANSLATE_NOOP("PetWindow", "Rest"),
    blink=(),  # no eyelids: it never blinks
)
