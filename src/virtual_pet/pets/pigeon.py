"""The pigeon: a blue-bar rock pigeon that walks bobbing its head and pecks at the ground.

The commonest form of the rock pigeon (Columba livia), wild or feral: a slate head with an orange
eye and a white cere over a dark beak, a neck shining green above and purple below, pale gray
wings with two black bars, dark flight feathers, a black band at the tip of the tail, and coral
feet. The proportions come from profile photos (iNaturalist 11465068 and 15982727), with the
head about 1.3 times its real size so that its eye reads. The body is about ten rows deep, as in
the photos; a deeper one with a belly bulging between the legs, and a smaller, slimmer pigeon,
were turned down. The neck is long enough for the head to stand above the shoulders.

The collar is the same in every pose: green on the upper neck, against the head, and a purple
patch of ten pixels at its base, on the breast side; only the head, when it sinks or bends,
hides some of the green. A purple line running the length of the bent neck was turned down.

WALKING is the pigeon's head bob. In each step the head holds still on the ground while the
body goes on, so in the frames it slides back a pixel a frame, as far as the window moves at
36 px/s and 12 fps; then it thrusts ahead two pixels a frame. It bobs once a step and thrusts
while a foot is in the air (studies give the hold phase as about half the cycle). Each foot is
down for five frames, its shank turning over it while it keeps still on the ground, and swings
through three: lifted behind, tucked up two rows, reaching forward. Legs drawn from one point,
which ran into a pink blob and dragged their feet along the ground, were turned down.

STANDING is pecking: it looks down (LOOK), leans over its feet with its tail up and its back
level, holds its head still a moment above the ground (AIM, the fixation pause before the
strike) and pecks twice (PECK, the beak on the ground line), then stands a while. The bent neck
arches smoothly from the back down to the head (a bump where it left the back was turned
down), and the eye turns with the head, its pupil toward the beak. SITTING is down on its belly,
the legs folded under it, the head sinking a pixel into the shoulders now and then.

CARRIED, it flaps above its body, as a held pigeon struggles: the near wing raised, showing its
pale underside and dark flight feathers, the far one dark behind it, then both swept back over
the tail; with the wing off its side, the flank shows slate. A wing beating down below the body
didn't read as a wing at this size.

The silhouette began as an egg sampled to pixels and checked against the photos, and the frames
were put together from the same head, body and legs, then fixed by hand; later edits go
straight into the frames below. It blinks as most pets do: pigeons blink with the upper lid.
"""

